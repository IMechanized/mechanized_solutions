import React from "react";
import Head from "next/head";
import Link from "next/link";
import useSWR, { useSWRConfig } from "swr";
import { useToasts } from "react-toast-notifications";
import sweetAlert from "sweetalert";
import { HiOutlineTrash } from "react-icons/hi";
import { BsEyeSlash } from "react-icons/bs";
import TableLarge from "../../../../src/components/dashboard/super-admin/category/table-large";
import DashboardLayout from "../../../../src/components/dashboard/dashboard-layout";
import { authAxios } from "../../../../src/utils/axiosKits";
import useUser, { UserNotLogin } from "../../../../src/lib/user";

const fetcher = (url) => authAxios.get(url).then((res) => res.data.data);

const AdsCategory = () => {
  const [categoryIds, setCategoryIds] = React.useState([]);
  const [loadingTop, setLoadingTop] = React.useState(false);

  const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
  const userData = user?.data;
  const adminEntry = isSuperAdmin || isAdmin;

  const { addToast } = useToasts();
  const { mutate } = useSWRConfig({
    refreshInterval: 0,
  });

  const { data: adsCategoryData, error: adsCategoryError } = useSWR(
    `/ads/admin/category`,
    fetcher
  );

  // delete multiple Category function
  const deleteMultipleCategory = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Category', {
        appearance: "warning",
        autoDismiss: true,
        autoDismissTimeout: 3000,
      });
      return
    }
    sweetAlert({
      title: "Are you sure?",
      text: "You want to delete these category?",
      icon: "warning",
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true);
        try {
          authAxios({
            method: "DELETE",
            url: `/ads/multiselect/category`,
            data: {
              categoryIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate("/ads/category").then(() => {
                addToast(res.data.message, {
                  appearance: "success",
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                });
                setLoadingTop(false);
              }, 1000);
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: "error",
                autoDismiss: true,
                autoDismissTimeout: 3000,
              });
              setLoadingTop(false);
            });
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: "error",
            autoDismiss: true,
            autoDismissTimeout: 3000,
          });
          setLoadingTop(false);
        }
      }
    });
  };

  // disable multiple Category function
  const disableMultipleCategory = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Category', {
        appearance: "warning",
        autoDismiss: true,
        autoDismissTimeout: 3000,
      });
      return
    }
    sweetAlert({
      title: "Are you sure?",
      text: "You want to disable these category?",
      icon: "warning",
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true);
        try {
          authAxios({
            method: "PUT",
            url: `/ads/multiselect/category/status`,
            data: {
              categoryIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate("/ads/category").then(() => {
                addToast(res.data.message, {
                  appearance: "success",
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                });
                setLoadingTop(false);
              }, 1000);
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: "error",
                autoDismiss: true,
                autoDismissTimeout: 3000,
              });
              setLoadingTop(false);
            });
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: "error",
            autoDismiss: true,
            autoDismissTimeout: 3000,
          });
          setLoadingTop(false);
        }
      }
    });
  };

  return (
    <>
      <Head>
        <title>Manage Category</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      {loggedOut && <UserNotLogin />}

      {userData && loggedIn && adminEntry && (
        <DashboardLayout>
          <section className="mb-16">
            <div className="flex flex-wrap sm:flex-nowrap items-center justify-between gap-5 sm:gap-0">
              <p className="text-2xl font-bold text-themeBlackAlt m-auto sm:m-0">
                Ads Category
              </p>
              <button className="bg-themePrimary rounded px-7 py-3 w-full sm:w-auto">
                <Link href="/dashboard/superadmin/category/add-category">
                  <a className="text-base font-semibold text-white">
                    Add New Category
                  </a>
                </Link>
              </button>
            </div>

            <div className="flex gap-2 pt-8 pb-4">
              <button
                className="bg-white p-3 rounded hover:bg-themePrimary group"
                onClick={() => disableMultipleCategory(categoryIds)}
              >
                <BsEyeSlash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
              <button
                className="bg-white p-3 rounded hover:bg-themeRedLight group"
                onClick={() => deleteMultipleCategory(categoryIds)}
              >
                <HiOutlineTrash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
            </div>

            <div className="flex flex-col">
              <TableLarge
                adsCategoryData={adsCategoryData}
                adsCategoryError={adsCategoryError}
                categoryIds={categoryIds}
                setCategoryIds={setCategoryIds}
                loadingTop={loadingTop}
              />
            </div>
          </section>
        </DashboardLayout>
      )}
    </>
  );
};

export default AdsCategory;
