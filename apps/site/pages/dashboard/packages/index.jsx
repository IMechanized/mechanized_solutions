import Head from 'next/head';
import Packages from '../../../src/components/dashboard/common-components/packages';
import DashboardLayout from '../../../src/components/dashboard/dashboard-layout';
import useUser, { UserGoBack, UserNotLogin } from '../../../src/lib/user';

const Package = () => {
    const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin } =
        useUser();
    const userData = user?.data;
    const adminEntry = isSuperAdmin || isAdmin;

    return (
        <>
            <Head>
                <title>Packages</title>
                <meta
                    name="description"
                    content="Generated by create next app"
                />
            </Head>

            {loggedOut && <UserNotLogin />}
            {isSeller && <UserGoBack />}
            {userData && loggedIn && (
                <DashboardLayout>
                    <main>
                        <Packages />
                    </main>
                </DashboardLayout>
            )}
        </>
    );
};

export default Package;
