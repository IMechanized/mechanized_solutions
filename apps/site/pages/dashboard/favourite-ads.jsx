import Head from 'next/head';
import Favourite from '../../src/components/dashboard/common-components/favourite-ads';
import DashboardLayout from '../../src/components/dashboard/dashboard-layout';
import useUser, { UserNotLogin } from '../../src/lib/user';

const FavouriteAds = () => {
    const { user, loggedIn, loggedOut } = useUser();
    const userData = user?.data;

    return (
        <>
            <Head>
                <title>Favorite ads</title>
                <meta
                    name="description"
                    content="Generated by create next app"
                />
            </Head>

            {loggedOut && <UserNotLogin />}
            {userData && loggedIn && (
                <DashboardLayout>
                    <Favourite />
                </DashboardLayout>
            )}
        </>
    );
};

export default FavouriteAds;
