import Head from 'next/head';
import { useRouter } from 'next/router';
import React from 'react';
import { AiOutlineNotification } from 'react-icons/ai';
import useSWR from 'swr';
import DashboardLayout from '../../../src/components/dashboard/dashboard-layout';
import { ThemeContext } from '../../../src/context/ThemeContext';
import { LoaderPage } from '../../../src/lib/loader';
import useUser, { UserNotLogin } from '../../../src/lib/user';
import { authAxios } from '../../../src/utils/axiosKits';

const fetcher = (url) => authAxios(url).then((res) => res.data.data);

const Reports = () => {
    const router = useRouter();

    const { recentNotification, recentNotificationError } =
        React.useContext(ThemeContext);
    const notificationData = recentNotification?.notification;

    const { user, loggedIn, loggedOut } = useUser();
    const userData = user?.data;

    const { data: adData, error: adError } = useSWR(
        `/user/ads/${router?.query?.active_id}`,
        fetcher,
        {
            refreshInterval: 0,
        },
    );

    const { data: adsReportData, error: adsReportError } = useSWR(
        `/user/report/ads/${router?.query?.active_id}`,
        fetcher,
        {
            refreshInterval: 0,
        },
    );

    return (
        <>
            <Head>
                <title>Ads Reports</title>
                <meta
                    name="description"
                    content="Generated by create next app"
                />
            </Head>

            {loggedOut && <UserNotLogin />}
            {userData && loggedIn && (
                <DashboardLayout>
                    <div className="shadow-card rounded bg-white pt-10 pb-8">
                        <div className="h-16 bg-themeDark flex items-center px-10 rounded-lg">
                            <p className="text-2xl font-semibold text-themeBlackDarker">
                                All Reports for{' '}
                                <span className="text-themePrimary font-bold">
                                    {adData?.adTitle}
                                </span>
                            </p>
                        </div>

                        <div className="!p-5 relative">
                            {!adData && (
                                <div className="h-60">
                                    <LoaderPage />
                                </div>
                            )}
                            {adError && (
                                <div className="h-40">
                                    <p className="text-center text-gray-600">
                                        Something went wrong. Please try again
                                        later.
                                    </p>
                                </div>
                            )}
                            {adData &&
                                adsReportData &&
                                _.map(adsReportData, (report, index) => (
                                    <div
                                        className="flex justify-between !p-2 !mb-2 border-b"
                                        key={index}
                                    >
                                        <div className="flex items-center gap-3 lg:gap-4 pb-3">
                                            <div>
                                                <div className="flex w-12 h-12 justify-center items-center rounded-full bg-red-300">
                                                    <AiOutlineNotification className="text-lg text-white " />
                                                </div>
                                            </div>
                                            <div>
                                                <p className="text-lg font-normal text-themeBlackDarker">
                                                    {report?.reason}
                                                </p>
                                            </div>
                                        </div>
                                        <div>
                                            <div className="text-sm text-themeWhiteLighter font-normal">
                                                {
                                                    report?.user?.fullName
                                                        ?.firstName
                                                }{' '}
                                                {
                                                    report?.user?.fullName
                                                        ?.lastName
                                                }
                                            </div>
                                            <div className="text-sm text-themeWhiteLighter font-normal">
                                                {report?.user?.email}
                                            </div>
                                        </div>
                                    </div>
                                ))}
                        </div>
                    </div>
                </DashboardLayout>
            )}
        </>
    );
};

export default Reports;
