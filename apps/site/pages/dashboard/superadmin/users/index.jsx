import React from "react";
import Head from "next/head";
import Link from "next/link";
import { useRouter } from 'next/router';
import { useToasts } from "react-toast-notifications";
import sweetAlert from "sweetalert";
import useSWR, { useSWRConfig } from "swr";
import Image from "../../../../src/optimize/image";
import { HiOutlineTrash } from "react-icons/hi";
import LargeTable from "../../../../src/components/dashboard/super-admin/users/large-table";
// import Pagination from "../../../../src/components/dashboard/super-admin/users/Pagination";
import DashboardLayout from "../../../../src/components/dashboard/dashboard-layout";
import SmallTable from "../../../../src/components/dashboard/super-admin/users/small-table";
import { authAxios } from "../../../../src/utils/axiosKits";
import Pagination from "../../../../src/components/fronted/pagination";
import useUser, { UserGoBack, UserNotLogin } from "../../../../src/lib/user";

const userMenu = [
  {
    id: 1,
    name: "All Users",
    role: "all",
  },
  {
    id: 2,
    name: "Super Admin",
    role: "super-admin",
  },
  {
    id: 3,
    name: "Admin",
    role: "admin",
  },
  {
    id: 4,
    name: "Buyer",
    role: "buyer",
  },
  {
    id: 5,
    name: "Seller",
    role: "seller",
  },
];
const fetcher = (url) => authAxios(url).then((res) => res.data.data);
const userAPI = "/admin/manage/user"

const Users = () => {
  const [active, setActive] = React.useState(0);
  const [currentPage, setCurrentPage] = React.useState(0);
  const [usersPerPage] = React.useState(10);
  const [userIds, setUserIds] = React.useState([]);
  const [loadingTop, setLoadingTop] = React.useState(false);

  const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
  const userDataMain = user?.data;
  const adminEntry = isSuperAdmin || isAdmin;

  const { addToast } = useToasts();

  const router = useRouter();
  const API = router.pathname == router.asPath ? userAPI + `?page=${currentPage}` : userAPI + router.asPath.replace(router.pathname, '') + `&page=${currentPage}`;
  const { data: totalUserData, error: userError } = useSWR(API, fetcher,
    {
      refreshInterval: 0,
    }
  );

  const userData = totalUserData?.users;
  const totalUserCount = totalUserData?.userCount;

  const userTypeChangeHandler = (userType) => {
    router.push({
      query: {
        role: userType,
      },
    })
  };

  const { mutate } = useSWRConfig({
    refreshInterval: 0,
  });

  // delete multiple user function
  const deleteMultipleUser = (ids) => {
    if (ids.length < 1) {
      return addToast("Please select at least one user", {
        appearance: "warning",
        autoDismiss: true,
        autoDismissTimeout: 3000,
      });
    }
    sweetAlert({
      title: "Are you sure?",
      text: "You want to delete these users?",
      icon: "warning",
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true);
        try {
          authAxios({
            method: "DELETE",
            url: `/admin/manage/multiselect/user`,
            data: {
              userIDs: `${ids}`,
            },
          })
            .then((res) => {
              mutate("/admin/manage/user")
                .then(() => {
                  addToast(res.data.message, {
                    appearance: "success",
                    autoDismiss: true,
                    autoDismissTimeout: 3000,
                  });
                  setLoadingTop(false);
                }, 1000);
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: "error",
                autoDismiss: true,
                autoDismissTimeout: 3000,
              });
              setLoadingTop(false);
            });
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: "error",
            autoDismiss: true,
            autoDismissTimeout: 3000,
          });
          setLoadingTop(false);
        }
      }
    });
  };

  const handlePageChange = (data) => {
    setCurrentPage(data.selected);
  };

  return (
    <>
      <Head>
        <title>Manage Users</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      <DashboardLayout>
        <main>
          {loggedOut && <UserNotLogin />}
          {isSeller && <UserGoBack />}
          {userData && loggedIn && adminEntry && (
            <section className="pb-32 h-screen">
              <div className="flex flex-wrap lg:flex-nowrap gap-4 lg:gap-0 items-center justify-between ">
                <h1 className="text-3xl font-bold text-themeBlackDarker">Users</h1>
                <div>
                  <ul className="flex flex-wrap lg:flex-nowrap items-center gap-3">
                    {userMenu.map((item, index) => (
                      <li
                        key={index}
                        onClick={() => {
                          setActive(index);
                          userTypeChangeHandler(item.role);
                        }}

                        className={`flex items-center gap-4 py-3 px-5 rounded-md cursor-pointer translate duration-300 ease-in-out ${active === index ? "bg-themePrimaryLighter" : "bg-white"
                          }`}
                      >
                        <span
                          className={`w-2 h-2 rounded-full ${active === index
                            ? "bg-themePrimary"
                            : "bg-white border border-themeGray"
                            }`}
                        ></span>
                        <span
                          className={`text-sm font-normal translate duration-300 ease-in-out ${active === index
                            ? "text-themePrimary"
                            : "text-themeBlackDarker"
                            }`}
                        >
                          {item.name}
                        </span>
                      </li>
                    ))}
                  </ul>
                </div>
              </div>

              <div className="flex gap-6 pt-8">
                <Link href="/dashboard/superadmin/users/add-user">
                  <a>
                    <button className="text-sm font-semibold text-white bg-themePrimary rounded py-3 px-5">
                      Add New User
                    </button>
                  </a>
                </Link>
                <button
                  type="submit"
                  className="bg-white p-3 rounded hover:bg-themeRedLight group"
                >
                  <HiOutlineTrash className="text-themeWhiteLighter text-xl group-hover:text-white"
                    onClick={() => deleteMultipleUser(userIds)}
                  />
                </button>
              </div>

              <div className="hidden sm:flex flex-col mt-6">
                {active === 0 && <LargeTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 1 && <LargeTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 2 && <LargeTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 3 && <LargeTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 4 && <LargeTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
              </div>

              <div className="sm:hidden mt-6">
                {active === 0 && <SmallTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 1 && <SmallTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 2 && <SmallTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 3 && <SmallTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
                {active === 4 && <SmallTable userData={userData} userError={userError} userIds={userIds} setUserIds={setUserIds} loadingTop={loadingTop} />}
              </div>

              <div className="flex flex-wrap  gap-4 sm:gap-0 items-center justify-center sm:justify-between pt-7">
                <div>
                  {/* <Pagination /> */}

                  {/* <!-- pagination --> */}
                  {totalUserCount > usersPerPage && (
                    <Pagination
                      totalCount={totalUserCount}
                      showPerPage={usersPerPage}
                      handlePageChange={handlePageChange}
                    />
                  )}
                </div>
                {
                  totalUserCount > 0 && (
                    <p className="text-sm font-normal text-themeBlackDarker">
                      Total {totalUserCount} User{totalUserCount > 1 && "s"} Available
                    </p>
                  )}

              </div>
            </section>
          )}
        </main>
      </DashboardLayout>
    </>
  );
};

export default Users;
