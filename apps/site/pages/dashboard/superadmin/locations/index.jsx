import React from "react";
import Head from "next/head";
import Link from "next/link";
import useSWR, { useSWRConfig } from "swr";
import { useToasts } from "react-toast-notifications";
import sweetAlert from "sweetalert";
import { HiOutlineTrash } from "react-icons/hi";
import { BsEyeSlash } from "react-icons/bs";
import TableLarge from "../../../../src/components/dashboard/super-admin/category/table-large";
import DashboardLayout from "../../../../src/components/dashboard/dashboard-layout";
import { authAxios } from "../../../../src/utils/axiosKits";
import useUser, { UserNotLogin } from "../../../../src/lib/user";
import LocationTable from "../../../../src/components/dashboard/super-admin/locations/location-table";

const fetcher = (url) => authAxios.get(url).then((res) => res.data.data);

const AdsLocation = () => {
  const [locationsIds, setLocationIds] = React.useState([]);
  const [loadingTop, setLoadingTop] = React.useState(false);

  const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
  const userData = user?.data;
  const adminEntry = isSuperAdmin || isAdmin;

  const { addToast } = useToasts();
  const { mutate } = useSWRConfig({
    refreshInterval: 0,
  });

  const { data: adsLocationData, error: adsLocationError } = useSWR(
    `/admin/private/topLocations`,
    fetcher
  );


  // delete multiple Locations function
  const deleteMultipleLocation = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Location', {
        appearance: "warning",
        autoDismiss: true,
        autoDismissTimeout: 3000,
      });
      return
    }
    sweetAlert({
      title: "Are you sure?",
      text: "You want to delete these location list?",
      icon: "warning",
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true);
        try {
          authAxios({
            method: "DELETE",
            url: `/admin/multiselect/topLocations`,
            data: {
              locationIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate("/admin/topLocations").then(() => {
                addToast(res.data.message, {
                  appearance: "success",
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                });
                setLoadingTop(false);
              }, 1000);
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: "error",
                autoDismiss: true,
                autoDismissTimeout: 3000,
              });
              setLoadingTop(false);
            });
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: "error",
            autoDismiss: true,
            autoDismissTimeout: 3000,
          });
          setLoadingTop(false);
        }
      }
    });
  };

  // disable multiple Location function
  const disableMultipleLocation = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Location', {
        appearance: "warning",
        autoDismiss: true,
        autoDismissTimeout: 3000,
      });
      return
    }
    sweetAlert({
      title: "Are you sure?",
      text: "You want to disable these location list?",
      icon: "warning",
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true);
        try {
          authAxios({
            method: "PUT",
            url: `/admin/multiselect/topLocations/status`,
            data: {
              locationIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate("/admin/topLocations").then(() => {
                addToast(res.data.message, {
                  appearance: "success",
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                });
                setLoadingTop(false);
              }, 1000);
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: "error",
                autoDismiss: true,
                autoDismissTimeout: 3000,
              });
              setLoadingTop(false);
            });
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: "error",
            autoDismiss: true,
            autoDismissTimeout: 3000,
          });
          setLoadingTop(false);
        }
      }
    });
  };

  return (
    <>
      <Head>
        <title>Top Locations</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      {loggedOut && <UserNotLogin />}

      {userData && loggedIn && adminEntry && (
        <DashboardLayout>
          <section className="mb-16">
            <div className="flex flex-wrap sm:flex-nowrap items-center justify-between gap-5 sm:gap-0">
              <p className="text-2xl font-bold text-themeBlackAlt m-auto sm:m-0">
                Ads Location
              </p>
              <button className="bg-themePrimary rounded px-7 py-3 w-full sm:w-auto">
                <Link href="/dashboard/superadmin/locations/add-location">
                  <a className="text-base font-semibold text-white">
                    Add New Location
                  </a>
                </Link>
              </button>
            </div>

            <div className="flex gap-2 pt-8 pb-4">
              <button
                className="bg-white p-3 rounded hover:bg-themePrimary group"
                onClick={() => disableMultipleLocation(locationsIds)}
              >
                <BsEyeSlash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
              <button
                className="bg-white p-3 rounded hover:bg-themeRedLight group"
                onClick={() => deleteMultipleLocation(locationsIds)}
              >
                <HiOutlineTrash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
            </div>

            <div className="flex flex-col">
              <LocationTable
                adsLocationData={adsLocationData}
                adsCategoryError={adsLocationError}
                locationsIds={locationsIds}
                setLocationIds={setLocationIds}
                loadingTop={loadingTop}
              />
            </div>
          </section>
        </DashboardLayout>
      )}
    </>
  );
};

export default AdsLocation;
