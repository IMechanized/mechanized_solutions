import { ContentState, convertToRaw, EditorState } from 'draft-js'
import draftToHtml from 'draftjs-to-html'
let htmlToDraft = null
if (typeof window === 'object') {
  htmlToDraft = require('html-to-draftjs').default
}
import dynamic from 'next/dynamic'
import Head from 'next/head'
import Link from 'next/link'
import { useRouter } from 'next/router'
import React from 'react'

const Editor = dynamic(
  () => import('react-draft-wysiwyg').then((mod) => mod.Editor),
  { ssr: false }
)
import 'react-draft-wysiwyg/dist/react-draft-wysiwyg.css'
import { useForm } from 'react-hook-form'
import { useToasts } from 'react-toast-notifications'
import useSWR, { useSWRConfig } from 'swr'
import { MultiSelect } from '../../../../src/components/dashboard/common-components/form/multi-select-dropdown'
import DashboardLayout from '../../../../src/components/dashboard/dashboard-layout'
import { ThemeContext } from '../../../../src/context/ThemeContext'
import useUser, { UserNotLogin } from '../../../../src/lib/user'
import ImageOpt from '../../../../src/optimize/image'
import { authAxios } from '../../../../src/utils/axiosKits'

const fetcher = (url) => authAxios.get(url).then((res) => res.data.data)

const EditBlogs = () => {
  const [photoImage, setPhotoImage] = React.useState(null)
  const { filtersData, filtersError } = React.useContext(ThemeContext)
  const [selectedTags, setSelectedTags] = React.useState([])
  const [newTags, setNewTags] = React.useState([])

  const [content, setContent] = React.useState('')
  const [editorState, setEditorState] = React.useState(
    EditorState.createEmpty()
  )

  const filterTags = filtersData?.tags

  const router = useRouter()
  const { addToast } = useToasts()
  const { mutate } = useSWRConfig({
    refreshInterval: 0,
  })

  const { data: blogData, error: logError } = useSWR(
    `/ads/blog/byId/${router.query.active_id}`,
    fetcher
  )

  const { user, isAdmin, isSuperAdmin, loggedIn, loggedOut } = useUser()
  const userData = user?.data
  const adminEntry = isSuperAdmin || isAdmin

  const {
    register,
    handleSubmit,
    watch,
    setValue,
    formState: { errors, isSubmitting },
  } = useForm()

  const onSubmit = async (data) => {
    if (photoImage === null) {
      return addToast('Please select a photo', {
        appearance: 'warning',
        autoDismiss: true,
      })
    }
    const formData = new FormData()
    formData.append('blogTitle', data.blogTitle)
    formData.append('description', content)
    formData.append('tags', JSON.stringify(data.tags))

    if (data?.blogImageFile) {
      formData.append('blogImage', data.blogImageFile[0])
    }
    try {
      await authAxios
        .put(`/ads/blog/${router.query.active_id}`, formData)
        .then((res) => {
          addToast(res.data.message, {
            appearance: 'success',
            autoDismiss: true,
          })
          mutate('/ads/blog')
          setPhotoImage(null)
          router.push('/dashboard/superadmin/blogs')
        })
    } catch (error) {
      if (error?.response?.data) {
        addToast(error.response.data.message, {
          appearance: 'error',
          autoDismiss: true,
        })
      } else {
        addToast(error?.message, {
          appearance: 'error',
          autoDismiss: true,
        })
      }
    }
  }

  React.useEffect(() => {
    if (blogData) {
      setValue('blogTitle', blogData?.blogTitle)
      setPhotoImage(blogData.avatar)
      setSelectedTags(blogData.tags)

      /** Convert html string to draft JS */
      const contentBlock = htmlToDraft(blogData.description)
      const contentState = ContentState.createFromBlockArray(
        contentBlock.contentBlocks
      )
      const editorState = EditorState.createWithContent(contentState)

      setEditorState(editorState)
    }
  }, [blogData, setValue])

  // photo image upload preview handler
  function photoPreview(e) {
    const file = e.target.files[0]
    const filePreview = URL.createObjectURL(file)
    setPhotoImage(filePreview)
  }

  const ImageFile = register('blogImageFile')

  return (
    <>
      <Head>
        <title>Edit Blog</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      {loggedOut && <UserNotLogin />}

      {userData && loggedIn && adminEntry && (
        <DashboardLayout>
          <section className="h-screen container">
            <div className="bg-white p-5 sm:p-10 mt-12 rounded-xl max-w-4xl mx-auto shadow-boxShadow">
              <div className="flex justify-between items-center">
                <h1 className="text-lg sm:text-xl font-bold text-themeBlackDarker">
                  Add New Blog
                </h1>
                <Link href="/dashboard/superadmin/blogs">
                  <a className="text-sm font-normal text-themePrimary">
                    Cancel
                  </a>
                </Link>
              </div>
              <div className="pt-7">
                <form onSubmit={handleSubmit(onSubmit)}>
                  {/* blog title */}
                  <label htmlFor="">
                    <p className="text-sm font-semibold text-themeGrayWhite pb-2">
                      Blog Title
                    </p>
                    <input
                      type="text"
                      className="w-full focus:outline-none py-3 px-3 rounded-md border border-themeGrayLight"
                      {...register('blogTitle', { required: true })}
                    />
                    {errors.blogTitle && (
                      <span className="text-red-400 text-sm italic">
                        This field is required
                      </span>
                    )}
                  </label>

                  {/* blog Image */}
                  <div className="pt-4">
                    <p className="text-sm font-semibold text-themeGrayWhite pb-2">
                      Upload Image
                    </p>
                    {photoImage && (
                      <span className="!mb-3 items-center flex gap-3">
                        <ImageOpt
                          src={photoImage}
                          style={{
                            minWidth: '100px',
                            minHeight: '100px',
                          }}
                          width={100}
                          height={100}
                          alt="img"
                        />
                        <button
                          type="button"
                          className="bg-red-300 mt-2 text-white py-1 p-2.5 text-xss rounded hover:bg-red-500"
                          onClick={() => {
                            setPhotoImage(null)
                            setValue('categoryIcon', '')
                          }}
                        >
                          Remove
                        </button>
                      </span>
                    )}
                    <label className="flex flex-col border border-dashed border-themeGray w-full h-14 rounded-md cursor-pointer">
                      <p className="text-sm font-normal text-themeGrayWhite text-center m-auto">
                        Choose or Drag and Drop SVG Icon
                      </p>
                      <input
                        type="file"
                        className="hidden"
                        {...ImageFile}
                        ref={ImageFile.ref}
                        onBlur={ImageFile.onBlur}
                        onChange={(event) => {
                          ImageFile.onChange(event)
                          photoPreview(event)
                        }}
                      />
                    </label>
                    {errors.blogImageFile && (
                      <span className="text-red-400 text-sm italic">
                        This field is required
                      </span>
                    )}
                  </div>

                  {/*blog description  */}
                  <div className="pt-4">
                    <p className="pb-2 text-sm font-semibold text-themeWhiteLighter">
                      Blog Description
                    </p>
                    <Editor
                      editorState={editorState}
                      wrapperClassName="wrapperClassName"
                      editorClassName="editorClassName"
                      toolbarClassName="toolbarClassName"
                      onEditorStateChange={(newState) => {
                        setEditorState(newState)
                        setContent(
                          draftToHtml(
                            convertToRaw(newState.getCurrentContent())
                          )
                        )
                      }}
                    />
                  </div>

                  <div className="pt-6">
                    <label className="w-full sm:w-9/12" htmlFor="">
                      <p className="text-sm font-semibold text-themeGrayWhite pb-2">
                        Tags
                      </p>
                      <MultiSelect
                        options={filterTags}
                        isObject={false}
                        validationSyntax={true}
                        // error={errors?.adTags}
                        name="tags"
                        register={register}
                        setValue={setValue}
                        setNewTags={setNewTags}
                        selectedValues={selectedTags}
                        emptyRecordMsg="No tags found"
                        placeholder="Select Tags"
                      />
                    </label>
                  </div>

                  <button
                    type="submit"
                    disabled={isSubmitting}
                    className="flex gap-2 text-base font-semibold text-white bg-themePrimary py-3 px-7 mt-7 rounded"
                  >
                    {isSubmitting ? 'Please wait...' : 'Update Blog'}
                    {/* spinner */}
                    {isSubmitting && (
                      <div className="flex items-center justify-center ">
                        <div className="w-5 h-5 border-b-2 border-white rounded-full animate-spin"></div>
                      </div>
                    )}
                  </button>
                </form>
              </div>
            </div>
          </section>
        </DashboardLayout>
      )}
    </>
  )
}

export default EditBlogs
