import Head from 'next/head';
import AllAds from '../../../src/components/dashboard/common-components/ads';
import DashboardLayout from '../../../src/components/dashboard/dashboard-layout';
import useUser, { UserGoBack, UserNotLogin } from '../../../src/lib/user';

const Ads = () => {
    const { user, loggedIn, loggedOut, isBuyer } = useUser();
    const userData = user?.data;

    return (
        <>
            <Head>
                <title>Manage ads</title>
                <meta
                    name="description"
                    content="Generated by create next app"
                />
            </Head>

            {loggedOut && <UserNotLogin />}
            {isBuyer && <UserGoBack />}
            {userData && loggedIn && !isBuyer && (
                <DashboardLayout>
                    <main>
                        <AllAds />
                    </main>
                </DashboardLayout>
            )}
        </>
    );
};

export default Ads;
