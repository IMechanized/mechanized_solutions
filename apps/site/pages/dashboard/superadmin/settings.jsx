import Head from "next/head";
import React from "react";
import DashboardLayout from "../../../src/components/dashboard/dashboard-layout";
import AnnouncementSettings from "../../../src/components/dashboard/super-admin/settings/announcement-settings";
import EmailSettings from "../../../src/components/dashboard/super-admin/settings/email-settings";
import FilterSettings from "../../../src/components/dashboard/super-admin/settings/filter-settings";
import useUser, { UserGoBack, UserNotLogin } from "../../../src/lib/user";

const Settings = () => {
  const [active, setActive] = React.useState(1);
  const [toggleState, setToggleState] = React.useState(1);

  const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
  const userData = user?.data;
  const adminEntry = isSuperAdmin || isAdmin;


  return (
    <>
      <Head>
        <title>Settings</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      <DashboardLayout>
        <main>
          {loggedOut && <UserNotLogin />}
          {isSeller && <UserGoBack />}
          {userData && loggedIn && adminEntry && (
            <section className="h-screen">
              <div className="grid lg:flex gap-7">
                <div className="grow max-w-xs">
                  <div className=" space-y-3 bg-white rounded-md p-6 shadow-boxShadow">
                    <button
                      onClick={() => setActive(1)}
                      className={`w-full py-3 rounded-md text-left px-5 ${active === 1
                        ? "bg-themePrimary text-white "
                        : "bg-white text-themeBlackDarker"
                        }`}
                    >
                      Email Settings
                    </button>
                    <button
                      onClick={() => setActive(2)}
                      className={`w-full py-3 rounded-md text-left px-5 ${active === 2
                        ? "bg-themePrimary text-white "
                        : "bg-white text-themeBlackDarker"
                        }`}
                    >
                      Filter Settings
                    </button>
                    <button
                      onClick={() => setActive(3)}
                      className={`w-full py-3 rounded-md text-left px-5 ${active === 3
                        ? "bg-themePrimary text-white "
                        : "bg-white text-themeBlackDarker"
                        }`}
                    >
                      Announcement
                    </button>
                  </div>
                </div>
                <div className="grow-1 bg-white px-7 py-10 rounded-xl shadow-boxShadow w-full">
                  {
                    (active === 1 && <EmailSettings />) ||
                    (active === 2 && <FilterSettings />) ||
                    (active === 3 && (<AnnouncementSettings />))
                  }
                </div>
              </div>
            </section>
          )}
        </main>
      </DashboardLayout>
    </>
  );
};

export default Settings;
