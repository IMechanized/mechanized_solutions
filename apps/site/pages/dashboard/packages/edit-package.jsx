import Head from 'next/head';
import DashboardLayout from '../../../src/components/dashboard/dashboard-layout';
import EditPackageMain from '../../../src/components/dashboard/super-admin/packages/add-package/edit-package-main';
import useUser, { UserGoBack, UserNotLogin } from '../../../src/lib/user';

const EditPackage = () => {
    const {
        user,
        loggedIn,
        loggedOut,
        isSeller,
        isBuyer,
        isAdmin,
        isSuperAdmin,
    } = useUser();
    const userData = user?.data;
    const adminEntry = isSuperAdmin || isAdmin;
    const userEntry = isSeller || isBuyer;

    return (
        <>
            <Head>
                <title>Edit Package</title>
                <meta
                    name="description"
                    content="Generated by create next app"
                />
            </Head>

            {loggedOut && <UserNotLogin />}
            {userEntry && <UserGoBack />}
            {userData && loggedIn && adminEntry && (
                <DashboardLayout>
                    <main>
                        <EditPackageMain />
                    </main>
                </DashboardLayout>
            )}
        </>
    );
};

export default EditPackage;
