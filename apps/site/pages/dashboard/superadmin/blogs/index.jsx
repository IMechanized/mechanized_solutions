import React from 'react'
import Head from 'next/head'
import Link from 'next/link'
import useSWR, { useSWRConfig } from 'swr'
import { useToasts } from 'react-toast-notifications'
import sweetAlert from 'sweetalert'
import { HiOutlineTrash } from 'react-icons/hi'
import { BsEyeSlash } from 'react-icons/bs'
import DashboardLayout from '../../../../src/components/dashboard/dashboard-layout'
import TableLarge from '../../../../src/components/dashboard/super-admin/blogs/table-large'
import { authAxios } from '../../../../src/utils/axiosKits'
import useUser, { UserNotLogin } from '../../../../src/lib/user'

const fetcher = (url) => authAxios.get(url).then((res) => res.data.data)

const AdsBlogs = () => {
  const [blogIds, setBlogIds] = React.useState([])
  const [loadingTop, setLoadingTop] = React.useState(false)

  const { addToast } = useToasts()
  const { mutate } = useSWRConfig({
    refreshInterval: 0,
  })

  const { user, isAdmin, isSuperAdmin, loggedIn, loggedOut } = useUser()
  const userData = user?.data
  const adminEntry = isSuperAdmin || isAdmin

  const { data: adsBlogsData, error: adsBlogsError } = useSWR(
    `ads/admin/blog`,
    fetcher
  )

  // delete multiple blogs function
  const deleteMultipleBlogs = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Blog', {
        appearance: 'warning',
        autoDismiss: true,
        autoDismissTimeout: 3000,
      })
      return
    }
    sweetAlert({
      title: 'Are you sure?',
      text: 'You want to delete these blog list?',
      icon: 'warning',
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true)
        try {
          authAxios({
            method: 'DELETE',
            url: `/ads/multiselect/blog`,
            data: {
              blogIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate('/ads/blog').then(() => {
                addToast(res.data.message, {
                  appearance: 'success',
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                })
                setLoadingTop(false)
              }, 1000)
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: 'error',
                autoDismiss: true,
                autoDismissTimeout: 3000,
              })
              setLoadingTop(false)
            })
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: 'error',
            autoDismiss: true,
            autoDismissTimeout: 3000,
          })
          setLoadingTop(false)
        }
      }
    })
  }

  // disable multiple Category function
  const disableMultipleBlogs = (ids) => {
    if (ids.length < 1) {
      addToast('Please select at least one Blog', {
        appearance: 'warning',
        autoDismiss: true,
        autoDismissTimeout: 3000,
      })
      return
    }
    sweetAlert({
      title: 'Are you sure?',
      text: 'You want to disable these blog list?',
      icon: 'warning',
      buttons: true,
      dangerMode: true,
    }).then((willDelete) => {
      if (willDelete) {
        setLoadingTop(true)
        try {
          authAxios({
            method: 'PUT',
            url: `/ads/multiselect/blog/status`,
            data: {
              blogIds: `${ids}`,
            },
          })
            .then((res) => {
              mutate('/ads/blog').then(() => {
                addToast(res.data.message, {
                  appearance: 'success',
                  autoDismiss: true,
                  autoDismissTimeout: 3000,
                })
                setLoadingTop(false)
              }, 1000)
            })
            .catch((err) => {
              addToast(err?.response?.data?.message, {
                appearance: 'error',
                autoDismiss: true,
                autoDismissTimeout: 3000,
              })
              setLoadingTop(false)
            })
        } catch (error) {
          addToast(error?.response?.data?.message, {
            appearance: 'error',
            autoDismiss: true,
            autoDismissTimeout: 3000,
          })
          setLoadingTop(false)
        }
      }
    })
  }

  return (
    <>
      <Head>
        <title>Manage Blogs</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      {loggedOut && <UserNotLogin />}

      {userData && loggedIn && adminEntry && (
        <DashboardLayout>
          <section className="mb-16">
            <div className="flex flex-wrap sm:flex-nowrap items-center justify-between gap-5 sm:gap-0">
              <p className="text-2xl font-bold text-themeBlackAlt m-auto sm:m-0">
                News and Blogs
              </p>
              <button className="bg-themePrimary rounded px-7 py-3 w-full sm:w-auto">
                <Link href="/dashboard/superadmin/blogs/add-blogs">
                  <a className="text-base font-semibold text-white">
                    Add New Blog
                  </a>
                </Link>
              </button>
            </div>

            <div className="flex gap-2 pt-8 pb-4">
              <button
                className="bg-white p-3 rounded hover:bg-themePrimary group"
                onClick={() => disableMultipleBlogs(blogIds)}
              >
                <BsEyeSlash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
              <button
                className="bg-white p-3 rounded hover:bg-themeRedLight group"
                onClick={() => deleteMultipleBlogs(blogIds)}
              >
                <HiOutlineTrash className="text-themeWhiteLighter text-xl group-hover:text-white" />
              </button>
            </div>

            <div className="flex flex-col">
              <TableLarge
                adsBlogsData={adsBlogsData}
                adsBlogsError={adsBlogsError}
                blogIds={blogIds}
                setBlogIds={setBlogIds}
                loadingTop={loadingTop}
              />
            </div>
          </section>
        </DashboardLayout>
      )}
    </>
  )
}

export default AdsBlogs
