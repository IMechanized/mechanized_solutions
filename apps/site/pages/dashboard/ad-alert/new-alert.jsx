import _ from 'lodash';
import Head from 'next/head';
import Link from 'next/link';
import { useRouter } from 'next/router';
import React from 'react';
import { useForm } from 'react-hook-form';
import { useToasts } from 'react-toast-notifications';
import { MultiSelect } from '../../../src/components/dashboard/common-components/form/multi-select-dropdown';
import DashboardLayout from '../../../src/components/dashboard/dashboard-layout';
import { ThemeContext } from '../../../src/context/ThemeContext';
import { LoaderPage } from '../../../src/lib/loader';
import useUser, { UserNotLogin } from '../../../src/lib/user';
import { authAxios } from '../../../src/utils/axiosKits';


const AddNewAlert = () => {
  const { adsCategoryData, adsCategoryError, filtersData, filtersError, topLocationData, topLocationError } = React.useContext(ThemeContext);
  const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
  const userData = user?.data;

  const router = useRouter();
  const { addToast } = useToasts();

  const {
    register,
    handleSubmit,
    setValue,
    reset,
    formState: { errors, isSubmitting },
  } = useForm({});

  const onSubmitHandler = async (data) => {
    const newData = {
      name: data.alertName,
      keyword: data.keyword,
      location: data.location,
      category: data.category,
      tags: data.tags,
      emailFrequency: data.frequency,
    };

    try {
      await authAxios({
        method: "POST",
        url: "/user/alert/ads",
        data: newData,
      }).then((res) => {
        if (res.status === 200 || res.status === 201) {
          addToast(res.data.message, {
            appearance: "success",
            autoDismiss: true,
          });
          // 600 millisecond delay
          new Promise((resolve) => setTimeout(resolve, 600));
          reset();
          router.push("/dashboard/ad-alert");
        }
      });
    } catch (error) {
      if (error?.response?.data) {
        addToast(error.response.data.message, {
          appearance: "error",
          autoDismiss: true,
        });
      } else {
        addToast(error.message, {
          appearance: "error",
          autoDismiss: true,
        });
      }
    }
  };

  return (
    <>
      <Head>
        <title>New Ad Alert</title>
        <meta name="description" content="Generated by create next app" />
      </Head>

      {loggedOut && <UserNotLogin />}

      {userData && loggedIn && (
        <DashboardLayout>
          <main>
            {loggedOut && <UserNotLogin />}
            {userData && loggedIn && (
              <section className="bg-themeWhiteLight h-screen">
                <div className="container mx-auto py-12 px-6 sm:px-0">
                  <div className="bg-white p-10 rounded-xl max-w-4xl mx-auto shadow-boxShadow">
                    <div className="flex justify-between">
                      <p className="text-xl font-bold text-themeBlackDarker">Add New Alert</p>
                      <Link href="/dashboard/ad-alert">
                        <a className="text-themePrimary text-base font-semibold">Cancel</a>
                      </Link>
                    </div>

                    <div className="pt-12 relative">
                      {adsCategoryError || filtersError || topLocationError && (
                        <div className="bg-red-300 my-2 text-white py-1 p-2.5 text-xss rounded text-center">Failed to load data</div>
                      )}
                      {!adsCategoryData && !filtersData && !topLocationData && (
                        <LoaderPage />
                      )}

                      <form onSubmit={handleSubmit(onSubmitHandler)}>
                        <div className="flex flex-wrap sm:flex-nowrap gap-6 w-full">
                          {/* alert Name */}
                          <label className="w-full" htmlFor="">
                            <p className="text-themeWhiteLighter text-sm font-semibold pb-2">Alert Name</p>
                            <input className="w-full focus:outline-none py-3 border border-borderS rounded-md px-3" type="text"
                              name="alertName"
                              {...register("alertName", { required: true })}
                            />
                            {errors?.alertName && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </label>

                          {/* alert keyword */}
                          <label className="w-full" htmlFor="">
                            <p className="text-themeWhiteLighter text-sm font-semibold pb-2">Keyword</p>
                            <input className="w-full focus:outline-none py-3 border border-borderS rounded-md px-3" type="text"
                              name="keyword"
                              {...register("keyword", { required: true })}
                            />
                            {errors?.keyword && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </label>
                        </div>

                        <div className="flex flex-wrap sm:flex-nowrap gap-6 w-full pt-6">

                          {/* alert category */}
                          <label className="w-full" htmlFor="">
                            <p className="text-themeWhiteLighter text-sm font-semibold pb-2">Category</p>
                            <div className="border border-borderS rounded w-full relative">
                              <select
                                name="category"
                                className="py-3 pl-3 rounded-lg focus:outline-none cursor-pointer bg-white appearance-none w-full text-themeBlackAlt selectDashboard"
                                {...register("category", { required: true })}
                              >
                                <option value="">Select Category</option>
                                {_.map(adsCategoryData, (category, index) =>
                                  <option key={index} value={category.categoryTitle}>{category.categoryTitle}</option>
                                )}
                              </select>
                            </div>
                            {errors?.category && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </label>

                          {/* alert location */}
                          <label className="w-full" htmlFor="">
                            <p className="text-themeWhiteLighter text-sm font-semibold pb-2">Location</p>
                            <div className=" border border-borderS rounded w-full relative">
                              <select
                                name="location"
                                className="py-3 pl-3 rounded-lg focus:outline-none cursor-pointer bg-white appearance-none w-full text-themeBlackAlt selectDashboard"
                                {...register("location", { required: true })}
                              >
                                <option value="">Select Location</option>
                                {_.map(topLocationData, (location, index) =>
                                  <option key={index} value={location.location}>{location.location}</option>
                                )}
                              </select>
                            </div>
                            {errors?.location && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </label>
                        </div>

                        <div className="flex flex-wrap sm:flex-nowrap gap-6 w-full pt-6">

                          {/* alert frequency */}
                          <label className="w-full" htmlFor="">
                            <p className="text-themeWhiteLighter text-sm font-semibold pb-2">Email Me</p>
                            <div className="h-14 border border-borderS rounded w-full relative">
                              <select
                                name="frequency"
                                className="py-3 pl-3 rounded-lg focus:outline-none cursor-pointer bg-white appearance-none w-full  text-themeBlackAlt selectDashboard"
                                {...register("frequency", { required: true })}
                              >
                                {_.map(["Daily", "Weekly", "Fortnightly", "Monthly"],
                                  (item, index) => (
                                    <option value={item} key={index}>
                                      {item}
                                    </option>
                                  )
                                )}
                              </select>
                            </div>
                            {errors?.frequency && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </label>

                          {/* alert tags */}
                          <div className="w-full">
                            <label className="block text-themeWhiteLighter text-sm font-semibold pb-2" htmlFor="">
                              Tags
                            </label>
                            <MultiSelect
                              options={filtersData?.tags}
                              isObject={false}
                              name="tags"
                              validationSyntax={{ required: true }}
                              error={errors?.tags}
                              register={register}
                              setValue={setValue}
                              emptyRecordMsg="No tags found"
                              placeholder="Add Tags..."
                              adAlert={true}
                            />
                            {errors?.tags && (
                              <p className="text-red-400 text-sm italic py-2">
                                This field is required
                              </p>
                            )}
                          </div>

                        </div>

                        <button
                          type="submit"
                          disabled={isSubmitting}
                          className="flex gap-2 bg-themePrimary text-white py-3 px-7 rounded-md mt-14">
                          {isSubmitting ? "Please wait..." : "Save Alert"}
                          {/* spinner */}
                          {isSubmitting && (
                            <div className="flex items-center justify-center ">
                              <div className="w-5 h-5 border-b-2 border-white rounded-full animate-spin"></div>
                            </div>
                          )}
                        </button>

                      </form>
                    </div>
                  </div>
                </div>
              </section>
            )}
          </main>
        </DashboardLayout>
      )}
    </>
  );
};

export default AddNewAlert;