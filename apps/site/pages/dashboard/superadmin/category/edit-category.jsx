import Head from "next/head";
import React from "react";
import DashboardLayout from "../../../../src/components/dashboard/dashboard-layout";
import EditCategoryForm from "../../../../src/components/dashboard/super-admin/category/edit-category-form";
import useUser, { UserGoBack, UserNotLogin } from "../../../../src/lib/user";

export default function EditCategory() {
    const { user, loggedIn, loggedOut, isSeller, isAdmin, isSuperAdmin, } = useUser();
    const userData = user?.data;
    const adminEntry = isSuperAdmin || isAdmin;
    return (
        <>
            <Head>
                <title>Edit Category</title>

                <meta name="description" content="Generated by create next app" />
            </Head>

            <DashboardLayout>
                <main>
                    {loggedOut && <UserNotLogin />}
                    {isSeller && <UserGoBack />}
                    {userData && loggedIn && adminEntry && <EditCategoryForm />}
                </main>
            </DashboardLayout>
        </>
    );
}
